"""Demo data: dev cases with results computed by a real eval run.

`backend/data/demo_seed.json` is generated by `make seed-file` from the last dev
eval run, so the deployed demo opens with real outputs and spends no tokens
until someone adds a new reply.
"""

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

from app import store

SEED_FILE = Path(__file__).resolve().parents[1] / "data" / "demo_seed.json"


def load_seed() -> int:
    if not SEED_FILE.is_file():
        return 0
    items = json.loads(SEED_FILE.read_text(encoding="utf-8"))
    start = datetime.now(timezone.utc) - timedelta(hours=len(items))
    for i, item in enumerate(items):
        received = (start + timedelta(minutes=37 * i)).isoformat(timespec="seconds")
        sid = store.create_submission(item["email"], item["name"], item["role_id"], item["reply"], item["cv"],
                                      status="processing", received_at=received)
        store.save_evaluation(sid, item["result"], item["result"].get("bucket"), item.get("provider", "seed"))
    return len(items)
